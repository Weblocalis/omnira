#!/usr/bin/env python3
"""
Regenerates the Bootstrap Icons subset (font + CSS) with ONLY the icons used by the app.

Run it after adding a new `bi-xxx` icon in index.html, the legal pages or assets/js/*.js:

    pip install fonttools brotli
    python3 tools/build-icons.py

It downloads bootstrap-icons@1.11.3 with `npm pack` into a temporary folder, scans the project
for `bi-<name>` classes and writes assets/vendor/bootstrap-icons-1.11.3/bootstrap-icons-subset.{woff2,css}.
Then bump CACHE_VERSION in service-worker.js.
"""
import json
import pathlib
import re
import subprocess
import sys
import tarfile
import tempfile

VERSION = "1.11.3"
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "vendor" / f"bootstrap-icons-{VERSION}"
SCAN = ["*.html", "assets/js/*.js", "assets/js/locales/*.js"]
# Icons whose name is built at runtime (none today): list them here so they are kept.
EXTRA = []


def used_icons(codepoints):
    names = set(EXTRA)
    for pattern in SCAN:
        for path in ROOT.glob(pattern):
            for name in re.findall(r"\bbi-([a-z0-9-]+)", path.read_text(encoding="utf-8")):
                if name in codepoints:
                    names.add(name)
    return sorted(names)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.check_call(["npm", "pack", f"bootstrap-icons@{VERSION}", "--silent"], cwd=tmp, stdout=subprocess.DEVNULL)
        with tarfile.open(next(pathlib.Path(tmp).glob("*.tgz"))) as tgz:
            tgz.extractall(tmp, filter="data")
        pkg = pathlib.Path(tmp) / "package"
        codepoints = json.loads((pkg / "font" / "bootstrap-icons.json").read_text())
        names = used_icons(codepoints)
        if not names:
            sys.exit("No bi-* icon found: nothing to do.")
        OUT.mkdir(parents=True, exist_ok=True)
        unicodes = ",".join("U+%04X" % codepoints[n] for n in names)
        subprocess.check_call([
            sys.executable, "-m", "fontTools.subset", str(pkg / "font" / "fonts" / "bootstrap-icons.woff2"),
            "--unicodes=" + unicodes, "--flavor=woff2", "--no-hinting", "--layout-features=", "--name-IDs=",
            "--output-file=" + str(OUT / "bootstrap-icons-subset.woff2"),
        ])
        (OUT / "LICENSE").write_bytes((pkg / "LICENSE").read_bytes())

    css = (
        f"/* Bootstrap Icons {VERSION} (MIT) - subset generated by tools/build-icons.py: only the icons used by the app. */\n"
        '@font-face{font-display:block;font-family:"bootstrap-icons";src:url("bootstrap-icons-subset.woff2") format("woff2")}\n'
        '.bi::before,[class^="bi-"]::before,[class*=" bi-"]::before{display:inline-block;font-family:bootstrap-icons!important;'
        "font-style:normal;font-weight:normal!important;font-variant:normal;text-transform:none;line-height:1;vertical-align:-.125em;"
        "-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}\n"
    )
    css += "".join('.bi-%s::before{content:"\\%x"}\n' % (n, codepoints[n]) for n in names)
    (OUT / "bootstrap-icons-subset.css").write_text(css, encoding="utf-8")
    print(f"{len(names)} icons: {', '.join(names)}")


if __name__ == "__main__":
    main()
